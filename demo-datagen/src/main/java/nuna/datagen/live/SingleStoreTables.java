package nuna.datagen.live;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import nuna.datagen.kit.Kit;
import nuna.datagen.world.Feed;
import nuna.datagen.world.LakeSchemas;
import org.apache.iceberg.Schema;
import org.apache.iceberg.types.Type;
import org.apache.iceberg.types.Types;

/**
 * The SingleStore side of every feed but the orders, for when Kafka is off (D50, amended 2026-11-24): a table per feed in
 * database {@code brokerage}, with the lake table's columns, and a change feed per table copying it into
 * {@code brokerage.singlestore}. Main's {@code sql} command writes both files demo.sh runs, demo/singlestore/
 * brokerage-feeds.sql and brokerage-feeds-pipelines.sql; a test holds them to this class.
 *
 * <p>Each row carries {@code seq}, its place in its feed, as its key: the rows are only ever inserted, so the change feed
 * runs append-only, and a table's row count is how many records went this way. Lists (financial_transactions' lots)
 * are JSON, timestamps DATETIME(6) in UTC.
 */
public final class SingleStoreTables {

    static final String SEQ = "seq";

    private SingleStoreTables() {
    }

    /** Each feed's columns but seq, in order: its lake table's, and financial_transactions' locate_id at the end. */
    public static Map<Feed, List<String>> columns(Kit kit) {
        Map<Feed, List<String>> columns = new EnumMap<>(Feed.class);
        for (Feed f : feeds()) {
            List<String> names = new ArrayList<>();
            for (Types.NestedField field : schema(f, kit).columns()) {
                names.add(field.name());
            }
            columns.put(f, names);
        }
        return columns;
    }

    static List<Feed> feeds() {
        return java.util.Arrays.stream(Feed.values()).filter(f -> f != Feed.ORDERS).toList();
    }

    private static Schema schema(Feed f, Kit kit) {
        Schema schema = LakeSchemas.schema(f, kit);
        if (f != Feed.FINANCIAL_TRANSACTIONS) {
            return schema;
        }
        List<Types.NestedField> fields = new ArrayList<>(schema.columns());
        fields.add(Types.NestedField.optional(schema.highestFieldId() + 1, LakeSchemas.LOCATE_ID,
            Types.StringType.get()));
        return new Schema(fields);
    }

    /** brokerage-feeds.sql: the tables. */
    public static String tables(Kit kit) {
        StringBuilder sql = new StringBuilder("""
            -- Generated by demo-datagen (Main sql, SingleStoreTables): the brokerage world's feeds in SingleStore, for when
            -- Kafka is off (D50, amended 2026-11-24, item 238). demo.sh runs it as root after brokerage.sql. Each row is
            -- one record of its feed, numbered by seq; brokerage-feeds-pipelines.sql copies each table into the lake.
            USE brokerage;
            """);
        for (Feed f : feeds()) {
            sql.append("CREATE TABLE IF NOT EXISTS ").append(f.table).append(" (\n  ").append(SEQ)
                .append(" BIGINT NOT NULL");
            for (Types.NestedField field : schema(f, kit).columns()) {
                sql.append(",\n  ").append(field.name()).append(' ').append(sqlType(field.type()));
            }
            sql.append(",\n  PRIMARY KEY (").append(SEQ).append("),\n  SHARD KEY (").append(SEQ).append("));\n");
        }
        return sql.toString();
    }

    /** brokerage-feeds-pipelines.sql: a change feed per table, each into its copy under brokerage.singlestore. */
    public static String pipelines() {
        StringBuilder sql = new StringBuilder("""
            -- Generated by demo-datagen (Main sql, SingleStoreTables): a change feed per table of brokerage-feeds.sql, each
            -- copying its table into brokerage.singlestore (the connector makes the namespace and the table on its first
            -- start). demo.sh runs it while Kafka is off and the generator writes these tables (D50, amended 2026-11-24,
            -- item 238), with the singlestore user's catalog token and the root password put in, then starts each, and
            -- stops them when Kafka is back. Append-only: the generator only ever inserts, so the feed stops at an update.
            USE brokerage;
            """);
        for (Feed f : feeds()) {
            sql.append("\nCREATE OR REPLACE PIPELINE ").append(pipeline(f)).append(" AS LOAD DATA CONNECTOR 'ChangeFeedConnector'\n")
                .append("CONFIG '{\"singlestore.url\": \"jdbc:mariadb://localhost:3306/brokerage\", \"singlestore.user\": \"root\",\n")
                .append("         \"singlestore.database\": \"brokerage\", \"singlestore.table\": \"").append(f.table)
                .append("\", \"singlestore.append-only\": \"true\",\n")
                .append("         \"iceberg.catalog.uri\": \"http://nuna-catalog:8181\", \"iceberg.catalog.warehouse\": \"lakehouse\",\n")
                .append("         \"iceberg.catalog.header.X-Iceberg-Access-Delegation\": \"vended-credentials\",\n")
                .append("         \"iceberg.namespace\": \"").append(Feed.SINGLESTORE_COPIES).append("\", \"iceberg.table\": \"")
                .append(f.table).append("\", \"commit.interval.ms\": \"15000\"}'\n")
                .append("CREDENTIALS '{\"singlestore.password\": \"${SINGLESTORE_ROOT_PASSWORD}\", \"iceberg.catalog.token\": \"${SINGLESTORE_TOKEN}\"}'\n")
                .append("BATCH_INTERVAL 1000\n")
                .append("REPLACE INTO TABLE lake_commits\n")
                .append("FORMAT JSON (\n")
                .append("  snapshot_id <- value::snapshot_id, source_table <- value::source_table, iceberg_table <- value::iceberg_table,\n")
                .append("  kind <- value::kind, rows_written <- value::rows_written, keys_deleted <- value::keys_deleted,\n")
                .append("  offsets <- value::offsets, gap_after <- value::gap_after, @committed_at <- value::committed_at)\n")
                .append("SET committed_at = FROM_UNIXTIME(@committed_at / 1000);\n");
        }
        return sql.toString();
    }

    /** The change feed's pipeline name. */
    public static String pipeline(Feed f) {
        return "brokerage_" + f.table + "_to_lake";
    }

    static String sqlType(Type type) {
        return switch (type) {
            case Types.LongType l -> "BIGINT";
            case Types.IntegerType i -> "INT";
            case Types.StringType s -> "TEXT";
            case Types.DateType d -> "DATE";
            case Types.BooleanType b -> "TINYINT(1)";
            case Types.DecimalType d -> "DECIMAL(" + d.precision() + ", " + d.scale() + ")";
            case Types.TimestampType t -> "DATETIME(6)";
            case Types.ListType l -> "JSON";
            default -> throw new IllegalArgumentException("no SingleStore type for " + type);
        };
    }
}
