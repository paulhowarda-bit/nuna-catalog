#!/usr/bin/env python3
"""Build the nuna docs' search index and their All pages page from the site map and the pages written so far.

    python docs/site/tools/index.py

Writes docs/site/assets/search-index.js (loaded by docs.js the first time a reader searches) and
docs/site/all-pages.html (every page in site-map order: the no-script way round the site). Run it after pages change.
Standard library only; it reads pages with check.py's parser.
"""
import datetime
import html
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check  # noqa: E402

SITE = check.SITE
SNIPPET = 240
SKIP_CLASSES = {'code', 'see-also', 'doc-sources', 'doc-head', 'diagram', 'shot', 'tab-list'}


def text_of(node):
    return check.norm(node.text())


def index_page(path):
    tree, _ = check.parse(path)
    art = next((n for n in tree.root.walk() if n.tag == 'article'), None)
    if art is None:
        return None
    lead = art.first('p', 'lead')
    entries, cur = [], None

    def visit(n):
        nonlocal cur
        for c in n.children:
            if isinstance(c, str):
                if cur is not None and len(cur[3]) < SNIPPET:
                    t = re.sub(r'\s+', ' ', c)
                    if t.strip():
                        cur[3] = (cur[3] + t)[:SNIPPET + 40]
                continue
            if c.tag in ('svg', 'pre', 'header') or set(c.classes) & SKIP_CLASSES:
                continue
            if c.tag in ('h2', 'h3', 'h4') and c.attrs.get('id'):
                cur = [c.attrs['id'], text_of(c), int(c.tag[1]), '']
                entries.append(cur)
                continue
            visit(c)
            if c.tag in ('p', 'li', 'dd', 'td', 'th', 'dt') and cur is not None and cur[3] and not cur[3].endswith(' '):
                cur[3] += ' '

    visit(art)
    for e in entries:
        s = re.sub(r'\s+', ' ', html.unescape(e[3])).strip()
        if len(s) > SNIPPET:
            s = s[:SNIPPET].rsplit(' ', 1)[0] + '…'
        e[3] = s
    return {'l': text_of(lead) if lead else '', 'h': entries}


def page_html(title, lead, body):
    return f'''<!doctype html>
<html lang="en" data-root="" data-page="all-pages">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)} · nuna docs</title>
  <meta name="description" content="{html.escape(lead)}">
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/docs.css">
  <script src="assets/theme.js"></script>
  <script src="assets/nav.js" defer></script>
  <script src="assets/docs.js" defer></script>
</head>
<body>
<a class="skip" href="#main">Skip to the content</a>
<header class="site-head" id="site-head">
  <a class="brand" href="index.html">nuna docs</a>
  <a class="all-pages" href="all-pages.html">All pages</a>
</header>
<div class="site">
  <nav class="site-nav" id="site-nav" aria-label="Documentation"></nav>
  <main id="main" tabindex="-1">
    <article class="doc" data-type="section">
      <header class="doc-head">
        <h1>{html.escape(title)}</h1>
        <p class="lead">{html.escape(lead)}</p>
      </header>
{body}
    </article>
  </main>
  <aside class="toc" id="toc" aria-label="On this page"></aside>
</div>
<footer class="site-foot" id="site-foot"></footer>
</body>
</html>
'''


def inline(s):
    """The site map's descriptions mark names with backticks; give them code elements."""
    parts = re.split(r'`([^`]+)`', s)
    return ''.join(html.escape(p) if i % 2 == 0 else f'<code>{html.escape(p)}</code>' for i, p in enumerate(parts))


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')


def main():
    nav, nav_pages = check.load_nav()
    order = [p for p in nav['root'] if p['u'] == 'index.html']
    sec_of = {}
    for band in nav['bands']:
        for s in band['sections']:
            for p in s['pages']:
                order.append(p)
                sec_of[p['u']] = s['title']
    pages, written = [], 0
    for p in order:
        path = os.path.join(SITE, p['u'])
        if not os.path.exists(path):
            continue
        x = index_page(path)
        if x is None:
            continue
        written += 1
        pages.append({'u': p['u'], 't': p['t'], 's': sec_of.get(p['u'], ''), 'y': p['y'], 'l': x['l'], 'h': x['h']})
    data = {'v': 1, 'built': datetime.date.today().isoformat(), 'pages': pages}
    out = os.path.join(SITE, 'assets', 'search-index.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by docs/site/tools/index.py from the pages written so far. Do not edit: run it again.\n')
        # The repository's secretShapes check reads `"…password…","…"` as a credential. Escaping one letter as
        # o leaves the text the reader searches unchanged and gives the check nothing to match.
        text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
        text = re.sub(r'(?i)(passw)o(rd)', r'\1\\u006f\2', text)
        f.write('window.NUNA_SEARCH = ' + text + ';\n')

    total = sum(len(s['pages']) for b in nav['bands'] for s in b['sections'])
    chunks = []
    for band in nav['bands']:
        chunks.append(f'      <h2 id="{slug(band["title"])}">{html.escape(band["title"])}</h2>')
        for s in band['sections']:
            chunks.append(f'      <h3 id="{s["id"]}">{html.escape(s["title"])}</h3>')
            chunks.append('      <ul class="cards">')
            for p in s['pages']:
                exists = os.path.exists(os.path.join(SITE, p['u']))
                tail = '' if exists else ' Not written yet.'
                chunks.append(f'        <li><a href="{p["u"]}"><span class="card-title">{html.escape(p["t"])}</span>'
                              f'<span class="card-text">{inline(p["d"])}{tail}</span></a></li>')
            chunks.append('      </ul>')
    lead = f'Every page of the nuna documentation, {total} in all, in the order of the side navigation.'
    with open(os.path.join(SITE, 'all-pages.html'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(page_html('All pages', lead, '\n'.join(chunks)))
    size = os.path.getsize(out)
    print(f'search index: {written} pages written of {total + 1}, {size // 1024} KB in assets/search-index.js; all-pages.html rebuilt')


if __name__ == '__main__':
    main()
